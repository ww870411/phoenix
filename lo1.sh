#!/usr/bin/env bash
# ==============================================================================
# Phoenix 项目 - 服务器一键部署/重启脚本
# 路径建议: /home/ww870411/25-26/lo1.sh
# 使用方法:
#   ./lo1.sh           # 默认交互模式（5秒无操作自动选择平滑更新，无需守候）
#   ./lo1.sh 1         # 直接执行平滑更新（零长停机，不重启数据库）
#   ./lo1.sh 2         # 直接执行全量重建（彻底 down 后再 up）
# ==============================================================================
set -euo pipefail

DEPLOY_DIR="/home/ww870411/25-26"
COMPOSE_FILE="lo1_new_server.yml"

# 1. 切换到项目部署目录
cd "${DEPLOY_DIR}"

echo "=================================================="
echo "🚀 Phoenix 服务自动更新与部署脚本"
echo "工作目录: ${DEPLOY_DIR}"
echo "编排文件: ${COMPOSE_FILE}"
echo "=================================================="

# 2. 模式选择（支持参数输入、交互选择、倒计时默认）
MODE="${1:-}"

if [[ -z "${MODE}" ]]; then
  echo "请选择部署模式："
  echo "  [1] 平滑更新（推荐）：后台静默拉取新镜像，旧服务不断连，秒级原地替换，数据库不重启"
  echo "  [2] 全量重建（传统）：先 down 彻底销毁所有容器与网络，再重新 up -d 创建启动"
  echo "--------------------------------------------------"
  CHOICE=""
  # read -t 5 倒计时 5 秒，若超时自动选择默认值 1，无需人守在终端前
  if read -t 5 -r -p "👉 请选择 [回车或 5 秒后默认选择 1]: " user_input; then
    CHOICE="${user_input}"
  else
    echo "" # 超时换行
    CHOICE="1"
  fi
  CHOICE="${CHOICE:-1}"
else
  CHOICE="${MODE}"
fi

echo ""

# 3. 执行对应的部署策略
case "${CHOICE}" in
  1|smooth|pull)
    echo "=================================================="
    echo "🌟 模式 [1]：开始平滑滚动更新（极短停机时间）"
    echo "=================================================="
    echo "📦 [步骤 1/2] 正在后台拉取最新镜像（当前旧容器正常提供服务）..."
    docker compose -f "${COMPOSE_FILE}" pull

    echo "🔄 [步骤 2/2] 正在原地秒级替换变更容器（数据库保持运行）..."
    docker compose -f "${COMPOSE_FILE}" up -d --remove-orphans
    ;;

  2|rebuild|down)
    echo "=================================================="
    echo "🛑 模式 [2]：开始全量停机重建"
    echo "=================================================="
    echo "🛑 [步骤 1/2] 正在停止并移除全部旧容器与网络..."
    docker compose -f "${COMPOSE_FILE}" down

    echo "▶️ [步骤 2/2] 正在拉取新镜像并启动所有容器..."
    docker compose -f "${COMPOSE_FILE}" up -d
    ;;

  *)
    echo "❌ 错误：无效的选项 '${CHOICE}'，请输入 1 或 2。" >&2
    exit 1
    ;;
esac

echo ""
echo "=================================================="
echo "✅ 部署执行完成！当前容器运行状态："
echo "=================================================="
docker compose -f "${COMPOSE_FILE}" ps
