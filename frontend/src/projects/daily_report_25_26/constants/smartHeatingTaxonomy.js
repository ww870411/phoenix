/**
 * 标准化采集点列表对象集合
 */
export const TAXONOMY_LIST = RAW_TAXONOMY_TUPLES.map(([order, level1, level2, pointName]) => ({
  order,
  level1,
  level2,
  pointName,
}));

/**
 * 采集点规范名称检索字典 (以 pointName 为 Key)
 */
export const TAXONOMY_MAP = new Map(
  TAXONOMY_LIST.map((item) => [item.pointName, item])
);

/**
 * 统一标准化采集点名称与分类解析函数
 * @param {string} rawName 原始内网采集点名称
 * @returns {{ order: number, level1: string, level2: string, pointName: string }}
 */
export function normalizePoint(rawName) {
  if (!rawName) return { order: 9999, level1: "未知", level2: "未知", pointName: "—" };
  const trimmed = String(rawName).trim();
  const standardName = POINT_ALIAS_MAP[trimmed] || trimmed;
  const match = TAXONOMY_MAP.get(standardName);
  if (match) {
    return { ...match };
  }
  return {
    order: 9999,
    level1: "其他",
    level2: "未归类",
    pointName: standardName,
  };
}
